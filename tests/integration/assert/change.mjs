// What one shipped change must leave, judged against what the repo's own checker says its route is (lib/oracle.mjs).
// Call it after pr-review, on the change branch, before the operator merges it.
import path from 'node:path'
import { oracle } from '../lib/oracle.mjs'

const jsonl = text => text.split('\n').filter(Boolean).map(l => JSON.parse(l))
const frontmatter = text => {
  const block = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? ''
  const pairs = block.split('\n').map(l => /^([\w-]+):\s*(.*)$/.exec(l)).filter(Boolean)
  return Object.fromEntries(pairs.map(m => [m[1], m[2].trim()]))
}
const section = (text, name) => new RegExp(`^## ${name}\\s*$`, 'm').test(text)

// README, Guides and sensors: changed tests must fail on the base for these, so the change must also have run red first.
const redFirst = (type, tier) => ['bugfix', 'incident'].includes(type) || (['feature', 'greenfield'].includes(type) && tier !== 'S')

export async function assertChange(c, sb, slug, { operator = 'operator', label = slug } = {}) {
  const dir = `.sdlc/changes/${slug}`
  const read = name => sb.read(`${dir}/${name}`)
  let o
  await c.check(`${label}: the checker can load the change`, () => { o = oracle(sb.dir, slug); return true })
  if (!o) return
  const t = `${label} (${o.type} ${o.tier})`

  await c.check(`${t}: done (nothing left on its route)`, () => o.next === null || `next: ${JSON.stringify(o.next)}; step ${o.step.verdict}: ${o.step.reason}`)
  await c.check(`${t}: on its change branch`, () => {
    const branch = sb.git('rev-parse', '--abbrev-ref', 'HEAD')
    return branch === `sdlc/${slug}` || branch
  })

  const intent = frontmatter(read('intent.md'))
  await c.check(`${t}: intent.md records type, tier and created`, () => (intent.type && intent.tier && intent.created) ? true : JSON.stringify(intent))
  await c.check(`${t}: no open questions in intent, spec, design or plan`, () => {
    const open = JSON.parse(sb.sdlc(['status', '--json']).stdout).open.filter(q => q.startsWith(`${slug}/`))
    return open.length === 0 || open.join('; ')
  })
  for (const stage of ['spec', 'design', 'plan'].filter(s => o.stages.includes(s))) {
    const file = stage === 'plan' ? o.plan : `${stage}.md`
    const text = read(file)
    await c.check(`${t}: ${file} has no code fences`, () => (text !== '' && !/^\s*```/m.test(text)) || (text === '' ? 'missing' : 'contains a code fence'))
    if (stage !== 'spec') await c.check(`${t}: ${file} has Files, Slices and Verification`, () => {
      const missing = ['Files', 'Slices', 'Verification'].filter(s => !section(text, s))
      return missing.length === 0 || `missing ## ${missing.join(', ## ')}`
    })
  }

  // A design gate on a change planned without design.md is the plan gate (graph.ts gateOf).
  const expected = o.gates.filter(g => o.stages.includes(g)).map(g => (g === 'design' && !sb.exists(`${dir}/design.md`) ? 'plan' : g))
  const approvals = jsonl(sb.read('.sdlc/approvals.jsonl')).filter(a => a.slug === slug)
  await c.check(`${t}: approved exactly the gates its route meets [${expected.join(', ') || 'none'}]`, () => {
    const got = [...new Set(approvals.map(a => a.stage))]
    const missing = expected.filter(g => !got.includes(g))
    const extra = got.filter(g => !expected.includes(g) && g !== 'impact')
    return (missing.length === 0 && extra.length === 0) || `missing ${missing.join(', ') || '-'}; unexpected ${extra.join(', ') || '-'}`
  })
  await c.check(`${t}: every approval is the operator's`, () =>
    approvals.every(a => a.by === operator) || approvals.map(a => `${a.stage} by ${a.by}`).join(', '))

  const runs = jsonl(read('runs.jsonl'))
  if (redFirst(o.type, o.tier)) await c.check(`${t}: a test ran red before the fix (test first)`, () => {
    const red = runs.findIndex(r => r.expectFail && !r.source)
    const green = runs.findLastIndex(r => !r.expectFail && r.exit === 0)
    return (red !== -1 && red < green) || (red === -1 ? 'no --expect-fail run recorded by the build' : 'the red run came after the last green run')
  })

  const v = frontmatter(read('verification.md'))
  await c.check(`${t}: verification.md generated by sdlc, passing`, () =>
    (v.generated === 'sdlc' && v.result === 'pass' && v.full === 'pass') || JSON.stringify(v))
  await c.check(`${t}: every required level passed [${o.levels.join(', ')}]`, () => {
    const got = Object.fromEntries((v.levels ?? '').split(/\s*,\s*|\s+/).filter(Boolean).map(p => p.split('=')))
    const bad = o.levels.filter(l => got[l] !== 'pass' && got[l] !== 'plan')
    return bad.length === 0 || bad.map(l => `${l}=${got[l] ?? 'absent'}`).join(', ')
  })

  const ratchet = JSON.parse(read('ratchet.json') || '{}')
  await c.check(`${t}: points recorded`, () => Number(intent.points) > 0 || `points: ${intent.points}`)
  await c.check(`${t}: every recorded node and slice is done`, () => {
    const slices = Object.entries(ratchet.slices ?? {}).map(([k, s]) => [`slice ${k}`, s])
    const open = [...Object.entries(ratchet.nodes ?? {}), ...slices].filter(([, n]) => n.status !== 'done')
    const blocked = ratchet.blocked ? ` blocked: ${JSON.stringify(ratchet.blocked)}` : ''
    return (open.length === 0 && !ratchet.blocked) || `${open.map(([k, n]) => `${k}=${n.status}`).join(', ')}${blocked}`
  })
  // checkpoint.ts commits each recorded slice as `sdlc/<slug>: slice <n>`.
  await c.check(`${t}: each slice was checkpointed by its own commit`, () => {
    const subjects = sb.git('log', '--format=%s', 'main..HEAD').split('\n')
    const missing = Object.keys(ratchet.slices ?? {}).filter(k => !subjects.includes(`sdlc/${slug}: slice ${k}`))
    return (Object.keys(ratchet.slices ?? {}).length > 0 && missing.length === 0) || `no checkpoint for slice(s) ${missing.join(', ') || '(none recorded)'}`
  })
  if (o.tier === 'L') await c.check(`${t}: an in-session review was recorded`, () =>
    sb.git('ls-files', dir).split('\n').some(f => /\/review[^/]*\.md$/.test(f)) || 'no review*.md committed')

  const pr = frontmatter(read('pr.md'))
  await c.check(`${t}: pr.md open on sdlc/${slug}`, () => (pr.state === 'open' && pr.branch === `sdlc/${slug}`) || JSON.stringify(pr))
  await c.check(`${t}: ship.json and pr.md committed`, () => {
    const tracked = sb.git('ls-files', dir).split('\n')
    const missing = ['ship.json', 'pr.md'].filter(f => !tracked.includes(`${dir}/${f}`))
    return missing.length === 0 || `not committed: ${missing.join(', ')}`
  })
  await c.check(`${t}: the PR was opened through gh`, () => {
    const body = `${path.sep}.sdlc${path.sep}changes${path.sep}${slug}${path.sep}pr.md`
    const calls = sb.read('../logs/gh.log').split('\n').filter(l => l.startsWith('pr create ') && l.endsWith(body))
    return calls.length === 1 || `${calls.length} gh pr create call(s) for ${slug}`
  })
  await c.check(`${t}: no scope drift`, () => {
    const r = JSON.parse(sb.sdlc(['scope-drift', slug, '--base', 'main', '--json']).stdout)
    return r.drift.length === 0 || r.drift.join(', ')
  })
  // status and next drop a finished change from STATE.md, so after review it may differ from the committed copy; that
  // edit alone is expected, as long as it names no change.
  await c.check(`${t}: tree clean, nothing unresolved, no waivers`, () => {
    const cleared = /^change:\s*$/m.test(sb.read('.sdlc/STATE.md'))
    const dirty = sb.git('status', '--porcelain').split('\n').filter(l => l && !(cleared && /^ ?M .sdlc\/STATE\.md$/.test(l))).join('\n')
    const waived = jsonl(sb.read('.sdlc/waivers.jsonl'))
    const unresolved = sb.exists('.sdlc/unresolved.json')
    if (dirty === '' && !unresolved && waived.length === 0) return true
    const why = [dirty && `dirty: ${dirty.split('\n').join('; ')}`, unresolved && 'unresolved.json present', waived.length && `${waived.length} waiver(s)`]
    return why.filter(Boolean).join(' | ')
  })
  // CI judges the committed branch in a fresh checkout, and its command runs append to runs.jsonl: a throwaway worktree
  // gives the same view and leaves the sandbox untouched.
  await c.check(`${t}: CI check blocks only on the human-approval rows it cannot verify offline`, () => {
    const committed = jsonl(sb.run('git', ['show', `HEAD:.sdlc/approvals.jsonl`]).stdout ?? '').filter(a => a.slug === slug)
    const res = sb.inWorktree(wt => JSON.parse(wt.sdlc(['check', '--at', 'ci', '--base', 'main', '--json']).stdout))
    const other = res.blocks.filter(b => b.sensor !== 'human-approval')
    const rows = res.humanRows.length
    if (other.length === 0 && rows === committed.length && (rows === 0 || res.blocks.length === 1)) return true
    const blocks = res.blocks.map(b => `${b.sensor}: ${b.message}`).join(' | ') || 'none'
    return `blocks: ${blocks}; ${rows} human row(s) for ${committed.length} committed approval(s)`
  })
  await c.check(`${t}: npm test passes on the branch`, () => {
    const r = sb.run('npm', ['test', '--silent'])
    return r.status === 0 || (r.stdout + r.stderr).trim().split('\n').slice(-3).join(' ')
  })
}
