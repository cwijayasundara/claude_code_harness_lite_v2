// Deterministic checks for the scenario suite (run-trials.sh S): each scenario must end shipped, with evidence.
// Usage: node assert-scenarios.mjs <greenfield|bugfix|refactor> <repo> <plugin-root>
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const [scenario, repo, plugin] = process.argv.slice(2)
const file = rel => path.join(repo, rel)
const read = rel => (fs.existsSync(file(rel)) ? fs.readFileSync(file(rel), 'utf8') : '')
const sdlc = (...args) => execFileSync('node', ['--disable-warning=ExperimentalWarning', path.join(plugin, 'scripts/sdlc.ts'), ...args], {
  cwd: repo, encoding: 'utf8', env: { ...process.env, CLAUDE_PROJECT_DIR: repo },
})
const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim()
const results = []
const check = async (name, fn) => {
  try {
    const ok = await fn()
    results.push([ok === true ? 'PASS' : 'FAIL', name, ok === true ? '' : String(ok)])
  } catch (err) {
    results.push(['FAIL', name, err.message.split('\n')[0]])
  }
}
const changes = () => JSON.parse(sdlc('status', '--json')).changes ?? []
const change = () => changes().find(c => !c.slug.startsWith('adhoc-')) ?? changes()[0]
const changeFile = name => read(`.sdlc/changes/${change().slug}/${name}`)
const approvals = () => read('.sdlc/approvals.jsonl').split('\n').filter(Boolean).map(l => JSON.parse(l))
const load = async rel => import(`${file(rel)}?t=${Date.now()}`)

// Every scenario: shipped, on a branch, clean, verified by sdlc, nothing unresolved.
await check('a change was recorded', () => Boolean(change()) || 'no change under .sdlc/changes')
await check('the change is done (shipped)', () => /^done/.test(change().command) || change().command)
await check('committed on a branch, not main', () => !/^(?:main|master)$/.test(git('rev-parse', '--abbrev-ref', 'HEAD')) || 'still on main')
await check('working tree is clean after ship', () => {
  const dirty = git('status', '--porcelain').split('\n').filter(l => l && !/\.sdlc\/(?:STATE\.md|usage\.jsonl)$/.test(l))
  return dirty.length === 0 || dirty.join('; ')
})
await check('no unresolved quality-gate findings', () => !fs.existsSync(file('.sdlc/unresolved.json')) || read('.sdlc/unresolved.json').slice(0, 200))
await check('verification.md was generated by sdlc and passed', () => {
  const v = changeFile('verification.md')
  return (/generated: sdlc/.test(v) && /result: pass/.test(v)) || 'missing or not passing'
})
await check('a red run was recorded (test first)', () => /"expectFail":true/.test(changeFile('runs.jsonl')) || 'no --expect-fail run in runs.jsonl')

if (scenario === 'greenfield') {
  await check('onboarding scaffolded a test script and CLAUDE.md', () => {
    const pkg = JSON.parse(read('package.json') || '{}')
    return (Boolean(pkg.scripts?.test) && read('CLAUDE.md') !== '') || 'package.json test script or CLAUDE.md missing'
  })
  await check('.sdlc/sensors.json is valid and runs the tests', () => {
    const c = JSON.parse(read('.sdlc/sensors.json'))
    return Object.values({ ...c.fast, ...c.full }).some(cmd => typeof cmd === 'string' && /test/.test(cmd)) || JSON.stringify(c)
  })
  await check('the first feature went through spec and plan', () => (changeFile('spec.md') !== '' && changeFile('plan.md') !== '') || `type ${change().type}, tier ${change().tier}`)
  await check('the person approved spec and plan', () => {
    const stages = approvals().filter(a => a.slug === change().slug).map(a => a.stage)
    return (stages.includes('spec') && stages.includes('plan')) || `approved: ${stages.join(', ') || 'none'}`
  })
  await check('hidden acceptance: convert(value, from, to)', async () => {
    const { convert } = await load('src/convert.js')
    const near = (a, b) => Math.abs(a - b) < 1e-6
    let threw = false
    try { convert(1, 'm', 'parsec') } catch (err) { threw = err instanceof RangeError }
    return (near(convert(1, 'km', 'm'), 1000) && near(convert(12, 'in', 'ft'), 1) && near(convert(1, 'mi', 'km'), 1.609344) && threw)
      || 'wrong values or no RangeError for an unknown unit'
  })
}

if (scenario === 'bugfix') {
  await check('classified as a tier L bugfix', () => (change().type === 'bugfix' && change().tier === 'L') || `${change().type} ${change().tier}`)
  await check('diagnosis wrote plan.md with a root cause', () => /root cause/i.test(changeFile('plan.md')) || 'plan.md has no root cause')
  await check('the person approved the fix plan before the fix', () => {
    const plan = approvals().find(a => a.slug === change().slug && a.stage === 'plan')
    return Boolean(plan) || 'no plan approval'
  })
  await check('hidden acceptance: SAVE20 takes 20% off, SAVE10 still 10%', async () => {
    const { Catalog } = await load('src/catalog/products.js')
    const { Cart } = await load('src/cart/cart.js')
    const { checkout } = await load('src/orders/orders.js')
    const cat = new Catalog(); cat.add({ sku: 'MUG-002', name: 'Mug', priceCents: 1000 })
    const cart = new Cart(cat); cart.add('MUG-002')
    return (checkout(cart, { code: 'SAVE20' }).totalCents === 800 && checkout(cart, { code: 'SAVE10' }).totalCents === 900)
      || JSON.stringify(checkout(cart, { code: 'SAVE20' }))
  })
}

if (scenario === 'refactor') {
  await check('classified as a refactor', () => change().type === 'refactor' || change().type)
  await check('discounts moved to src/orders/discounts.js with rateFor(code)', async () => {
    const { rateFor } = await load('src/orders/discounts.js')
    return (rateFor('SAVE10') === 0.1 && rateFor('SAVE20') === 0.2) || 'rateFor gives wrong rates'
  })
  await check('orders.js no longer defines the codes', () => !/SAVE10\s*:/.test(read('src/orders/orders.js')) || 'codes still in orders.js')
  await check('hidden acceptance: checkout behaviour unchanged', async () => {
    const { Catalog } = await load('src/catalog/products.js')
    const { Cart } = await load('src/cart/cart.js')
    const { checkout } = await load('src/orders/orders.js')
    const cat = new Catalog(); cat.add({ sku: 'MUG-002', name: 'Mug', priceCents: 1200 })
    const cart = new Cart(cat); cart.add('MUG-002', 2)
    let unknown = false
    try { checkout(cart, { code: 'FREE' }) } catch (err) { unknown = /unknown discount/.test(err.message) }
    return (checkout(cart, { code: 'SAVE10' }).totalCents === 2160 && checkout(cart).totalCents === 2400 && unknown) || 'checkout behaviour changed'
  })
}

for (const [status, name, why] of results) console.log(`${status}  ${name}${why ? `  (${why})` : ''}`)
const failed = results.filter(r => r[0] === 'FAIL').length
console.log(`${scenario}: ${results.length - failed}/${results.length} checks passed`)
process.exitCode = failed ? 1 : 0
