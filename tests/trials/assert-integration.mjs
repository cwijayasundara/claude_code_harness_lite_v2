// Deterministic checks for the harness integration test (run-trials.sh I): what /sdlc:onboard and one change must leave.
// Usage: node assert-integration.mjs <onboard|change> <repo> <plugin-root>
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const [phase, repo, plugin] = process.argv.slice(2)
const file = rel => path.join(repo, rel)
const read = rel => (fs.existsSync(file(rel)) ? fs.readFileSync(file(rel), 'utf8') : '')
const sdlc = (...args) => execFileSync('node', ['--disable-warning=ExperimentalWarning', path.join(plugin, 'scripts/sdlc.ts'), ...args], {
  cwd: repo, encoding: 'utf8', env: { ...process.env, CLAUDE_PROJECT_DIR: repo },
})
const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim()
const results = []
const check = (name, fn) => {
  try {
    const ok = fn()
    results.push([ok === true ? 'PASS' : 'FAIL', name, ok === true ? '' : String(ok)])
  } catch (err) {
    results.push(['FAIL', name, err.message.split('\n')[0]])
  }
}
const wikiClean = () => {
  const s = JSON.parse(sdlc('wiki', 'status', '--json'))
  return s.none ? 'no manifest' : [...s.stale, ...s.missing, ...s.uncovered].length === 0 || JSON.stringify(s)
}

if (phase === 'onboard') {
  check('CLAUDE.md exists, at most 120 lines', () => {
    const n = read('CLAUDE.md').split('\n').length
    return (read('CLAUDE.md') !== '' && n <= 120) || `${n} lines`
  })
  check('CLAUDE.md carries the sdlc routing line', () => /sdlc routes all work in this repo/.test(read('CLAUDE.md')))
  check('.sdlc/sensors.json declares a test command', () => {
    const c = JSON.parse(read('.sdlc/sensors.json'))
    return Object.values({ ...c.fast, ...c.full }).some(cmd => /test/.test(cmd)) || JSON.stringify(c)
  })
  check('wiki index has a Mermaid module map', () => /```mermaid/.test(read('docs/wiki/index.md')))
  check('wiki covers at least 3 modules', () => {
    const pages = Object.keys(JSON.parse(read('docs/wiki/manifest.json')).pages)
    return pages.length >= 3 || pages.join(', ')
  })
  check('every wiki page file exists', () => {
    const pages = Object.keys(JSON.parse(read('docs/wiki/manifest.json')).pages)
    const absent = pages.filter(p => !fs.existsSync(file(`docs/wiki/${p}`)))
    return absent.length === 0 || absent.join(', ')
  })
  check('wiki status is clean (stamped, nothing uncovered)', wikiClean)
  check('wiki pages cite path:line', () => {
    const pages = Object.keys(JSON.parse(read('docs/wiki/manifest.json')).pages)
    return pages.every(p => /\w+\.\w+:\d+/.test(read(`docs/wiki/${p}`))) || 'a page has no path:line citation'
  })
}

if (phase === 'change') {
  check('the change is done (shipped)', () => /\bdone\b/.test(sdlc('status')) || sdlc('status'))
  check('committed on an sdlc/ branch', () => /^sdlc\//.test(git('rev-parse', '--abbrev-ref', 'HEAD')) || git('rev-parse', '--abbrev-ref', 'HEAD'))
  check('working tree is clean after ship', () => {
    const dirty = git('status', '--porcelain').split('\n').filter(l => l && !/\.sdlc\/(?:STATE\.md|usage\.jsonl)$/.test(l))
    return dirty.length === 0 || dirty.join('; ')
  })
  check('no unresolved quality-gate findings', () => !fs.existsSync(file('.sdlc/unresolved.json')) || read('.sdlc/unresolved.json'))
  check('verification.md was generated by sdlc and passed', () => {
    const v = execFileSync('git', ['ls-files', '.sdlc/changes'], { cwd: repo, encoding: 'utf8' }).split('\n').find(f => f.endsWith('verification.md'))
    const text = v ? read(v) : ''
    return (/generated: sdlc/.test(text) && /result: pass/.test(text)) || 'missing or not passing'
  })
  check('wiki status is clean after ship', wikiClean)
  check('orders wiki page records the change', () => {
    const page = Object.keys(JSON.parse(read('docs/wiki/manifest.json')).pages).find(p => /order/i.test(p))
    const text = page ? read(`docs/wiki/${page}`) : ''
    return (/bestSellers/.test(text) && /Recent changes[\s\S]*-\s+\S+/.test(text)) || `page ${page ?? '(none)'} lacks bestSellers or a recent-changes line`
  })
  const mod = path.join(repo, 'src/orders/report.js')
  try {
    const { bestSellers } = await import(mod)
    const orders = [
      { lines: [{ sku: 'TEA-001', qty: 2 }, { sku: 'MUG-002', qty: 1 }] },
      { lines: [{ sku: 'MUG-002', qty: 1 }, { sku: 'CUP-003', qty: 2 }] },
      { lines: [{ sku: 'TEA-001', qty: 1 }] },
    ]
    const top = bestSellers(orders, 2)
    const ok = JSON.stringify(top) === JSON.stringify(['TEA-001', 'CUP-003']) && JSON.stringify(bestSellers([], 3)) === '[]'
    results.push([ok ? 'PASS' : 'FAIL', 'hidden acceptance: bestSellers(orders, n)', ok ? '' : JSON.stringify(top)])
  } catch (err) {
    results.push(['FAIL', 'hidden acceptance: bestSellers(orders, n)', err.message.split('\n')[0]])
  }
}

for (const [status, name, why] of results) console.log(`${status}  ${name}${why ? `  (${why})` : ''}`)
const failed = results.filter(r => r[0] === 'FAIL').length
console.log(`${phase}: ${results.length - failed}/${results.length} checks passed`)
process.exitCode = failed ? 1 : 0
